import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';
import { mkdir } from 'node:fs/promises';
const screenshots = resolve('screenshots');
async function open(page, id) { await page.locator(`.cover-open[data-id="${id}"]`).click(); }
async function close(page) { await page.locator('[data-action="close-reader"]').click(); await expect(page.locator('.reader')).toHaveCount(0); }
test('desktop library: real TXT, EPUB, PDF, imports, bookmarks and persistence', async ({page}) => {
  const errors=[]; page.on('pageerror', e=>errors.push(e.stack));
  page.on('console', m=> { if (m.type()==='error' && !/sandboxed|Permissions policy violation: unload|server responded with a status of 404/.test(m.text())) errors.push(m.text()); });
  await mkdir(screenshots, {recursive:true});
  await page.goto('/');
  await expect(page.locator('.book-card')).toHaveCount(6);
  await page.screenshot({path:resolve(screenshots,'desktop.png'), fullPage:true});
  await page.locator('[data-action="tab"][data-tab="PDF"]').click();
  await expect(page.locator('.book-card')).toHaveCount(2);
  await page.locator('[data-action="tab"][data-tab="全部"]').click();
  await page.locator('#book-search').fill('山野');
  await expect(page.locator('.book-card')).toHaveCount(1);
  await page.locator('#book-search').fill('');
  await open(page,'demo-mountain');
  await expect(page.locator('.text-article')).toContainText('山');
  await page.locator('.reader-footer [data-action="next"]').click();
  const chapter=await page.locator('.text-article h1').textContent();
  await page.locator('[data-action="add-mark"]').click();
  await page.screenshot({path:resolve(screenshots,'txt-reader.png')});
  await close(page);
  await open(page,'demo-mountain');
  await expect(page.locator('.text-article h1')).toHaveText(chapter);
  await close(page);
  await page.locator('.sidebar [data-view="bookmarks"]').click();
  await expect(page.locator('.bookmark-card')).toHaveCount(1);
  await page.locator('[data-action="open-mark"]').click();
  await expect(page.locator('.text-article h1')).toHaveText(chapter);
  await close(page);
  await page.locator('.sidebar button[data-view="library"]').click();
  await open(page,'demo-moon');
  await expect(page.locator('.epub-viewport iframe')).toHaveCount(1,{timeout:20000});
  await expect(page.frameLocator('.epub-viewport iframe').locator('body')).toContainText('窗',{timeout:15000});
  await page.screenshot({path:resolve(screenshots,'epub-reader.png')});
  await page.locator('[data-action="toc"]').click();
  await expect(page.locator('[data-action="jump-epub"]')).toHaveCount(3);
  await page.locator('[data-action="jump-epub"]').nth(1).click();
  await expect(page.locator('#reader-chapter-label')).toContainText('第二章',{timeout:10000});
  await page.locator('[data-action="add-mark"]').click();
  await close(page);
  await open(page,'demo-moon');
  await expect(page.locator('#reader-chapter-label')).toContainText('第二章');
  await close(page);
  await open(page,'demo-art');
  await expect(page.locator('#pdf-canvas')).toBeVisible({timeout:20000});
  await expect(page.locator('#reader-chapter-label')).toContainText('共 3 页');
  await page.locator('.reader-footer [data-action="next"]').click();
  await expect(page.locator('#reader-chapter-label')).toContainText('第 2 页');
  await page.screenshot({path:resolve(screenshots,'pdf-reader.png')});
  await close(page);
  await open(page,'demo-art');
  await expect(page.locator('#reader-chapter-label')).toContainText('第 2 页');
  await close(page);
  const file={name:'我的测试小说.txt',mimeType:'text/plain',buffer:Buffer.from('第一章 山风\n这是我导入的中文小说。\n第二章 归途\n进度可以保存。')};
  await page.locator('#file-input').setInputFiles(file);
  await expect(page.locator('.book-card')).toHaveCount(7);
  await page.locator('#file-input').setInputFiles(file);
  await expect(page.locator('#toast-region')).toContainText('重复');
  await expect(page.locator('.book-card')).toHaveCount(7);
  await page.reload(); await expect(page.locator('.book-card')).toHaveCount(7);
  await page.getByRole('button',{name:'阅读《我的测试小说》',exact:true}).click();
  await expect(page.locator('.text-article')).toContainText('这是我导入的中文小说');
  await close(page);
  await page.locator('.sidebar [data-view="cloud"]').click();
  await expect(page.locator('.page-content')).toContainText('尚未接入');
  expect(errors).toEqual([]);
});
test('mobile layout and all reader types at 390px', async ({browser})=>{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const page=await context.newPage();
  await page.goto('/'); await expect(page.locator('.book-card')).toHaveCount(6);
  await page.screenshot({path:resolve(screenshots,'mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await open(page,'demo-mountain'); await expect(page.locator('.text-article')).toBeVisible();
  await page.screenshot({path:resolve(screenshots,'mobile-reader.png')}); await close(page);
  await open(page,'demo-moon'); await expect(page.locator('.epub-viewport iframe')).toHaveCount(1);
  await expect(page.frameLocator('.epub-viewport iframe').locator('body')).toContainText('窗'); await close(page);
  await open(page,'demo-art'); await expect(page.locator('#pdf-canvas')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await context.close();
});
test('LAN HTTP imports work without secure-context crypto APIs',async ({browser})=>{
  const {networkInterfaces}=await import('node:os');
  const ip=Object.values(networkInterfaces()).flat().find(i=>i.family==='IPv4'&&!i.internal)?.address;
  test.skip(!ip, 'No LAN address');
  const context=await browser.newContext(); const page=await context.newPage();
  await page.goto(`http://${ip}:4173`); await expect(page.locator('.book-card')).toHaveCount(6);
  expect(await page.evaluate(()=>isSecureContext)).toBe(false);
  await page.locator('#file-input').setInputFiles({name:'局域网测试.txt',mimeType:'text/plain',buffer:Buffer.from('第一章 你好\n手机局域网导入成功。')});
  await expect(page.locator('.book-card')).toHaveCount(7);
  await page.getByRole('button',{name:'阅读《局域网测试》',exact:true}).click();
  await expect(page.locator('.text-article')).toContainText('手机局域网导入成功');
  await page.locator('[data-action="add-mark"]').click();
  await expect(page.locator('#toast-region')).toContainText('已留下这一页');
  await context.close();
});


